#!/usr/bin/env python3
"""Builds the web (Emscripten / WebAssembly) version of Peepo Drum Kit.

    python web/build.py            # release build into web/dist
    python web/build.py --debug    # -O0 -g build with assertions
    python web/build.py --serve    # build, then serve web/dist on http://localhost:8080

Requires an activated Emscripten SDK (em++ on the PATH or the EMSDK environment variable set)
and git (to fetch the pinned Dear ImGui and ThorVG sources into web/deps).
The desktop build (xmake) is completely unaffected by this script.
"""
import argparse
import concurrent.futures
import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

WEB = Path(__file__).resolve().parent
ROOT = WEB.parent
DEPS = WEB / "deps"

# NOTE: Same versions as the xmake packages used by the desktop build
DEP_REPOS = {
    "imgui": ("https://github.com/ocornut/imgui", "v1.92.0-docking"),
    "thorvg": ("https://github.com/thorvg/thorvg", "v1.0-pre10"),
    # NOTE: stb has no tags, this is the commit of the xmake "stb 2025.03.14" package. Only stb_vorbis.c is used by the web build
    "stb": ("https://github.com/nothings/stb", "f0569113c93ad095470c54bf34a17b36646bbbb5"),
}

THORVG_CONFIG_H = """#pragma once
// Generated by web/build.py (replaces the meson generated config.h): software rasterizer + SVG loader only, no threads
#define THORVG_VERSION_STRING "1.0.0"
#define THORVG_SW_RASTER_SUPPORT 1
#define THORVG_SVG_LOADER_SUPPORT 1
#define THORVG_FILE_IO_SUPPORT 1
"""

DEFAULT_FONT = "NotoSansCJKjp-Regular.otf"


def find_emscripten():
    """Returns the em++ / emcc command prefixes as lists."""
    suffixes = [".exe", ".bat", ".cmd", ""] if os.name == "nt" else [""]
    candidates = []
    if os.environ.get("EMSDK"):
        candidates.append(Path(os.environ["EMSDK"]) / "upstream" / "emscripten")
    on_path = shutil.which("em++")
    if on_path:
        candidates.append(Path(on_path).parent)
    # NOTE: Convenience fallback for an emsdk checkout right next to this repository
    candidates.append(ROOT.parent / "emsdk" / "upstream" / "emscripten")
    for directory in candidates:
        for suffix in suffixes:
            if (directory / ("em++" + suffix)).is_file():
                return [str(directory / ("em++" + suffix))], [str(directory / ("emcc" + suffix))]
    sys.exit("error: Emscripten not found. Install the Emscripten SDK and either run its emsdk_env script "
             "or set the EMSDK environment variable (see web/README.md).")


def run(cmd, **kwargs):
    result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, encoding="utf-8", errors="replace", **kwargs)
    return result.returncode, result.stdout


def fetch_deps():
    DEPS.mkdir(exist_ok=True)
    if not (ROOT / "libs" / "dr_libs" / "dr_wav.h").exists():
        print("[deps] initializing the dr_libs git submodule")
        code, out = run(["git", "-C", str(ROOT), "submodule", "update", "--init", "libs/dr_libs"])
        if code != 0:
            sys.exit(out)
    for name, (url, tag) in DEP_REPOS.items():
        target = DEPS / name
        if target.exists():
            continue
        print(f"[deps] fetching {name} {tag}")
        # NOTE: Works for tags as well as plain commit hashes
        for cmd in (["git", "init", "-q", str(target)],
                    ["git", "-C", str(target), "fetch", "-q", "--depth", "1", url, tag],
                    ["git", "-C", str(target), "-c", "advice.detachedHead=false", "checkout", "-q", "FETCH_HEAD"]):
            code, out = run(cmd)
            if code != 0:
                shutil.rmtree(target, ignore_errors=True)
                sys.exit(f"error: failed to fetch {name}: {out}")
    config_dir = DEPS / "thorvg_config"
    config_dir.mkdir(exist_ok=True)
    config_h = config_dir / "config.h"
    if not config_h.exists() or config_h.read_text() != THORVG_CONFIG_H:
        config_h.write_text(THORVG_CONFIG_H)


def glob(base, *patterns):
    files = []
    for pattern in patterns:
        files += sorted(base.glob(pattern))
    return files


def collect_sources():
    src = ROOT / "src"
    imgui = DEPS / "imgui"
    thorvg = DEPS / "thorvg" / "src"

    # NOTE: Mirrors the add_files() list of xmake.lua. Desktop only files are guarded by #ifndef __EMSCRIPTEN__ and compile to nothing
    app = [src / "main.cpp"] + glob(src, "core/*.cpp", "peepodrumkit/*.cpp", "audio/*.c", "audio/*.cpp", "imgui/*.cpp",
                                    "imgui/ImGuiColorTextEdit/*.cpp", "imgui/extension/*.cpp")
    third_party = [imgui / f for f in ("imgui.cpp", "imgui_demo.cpp", "imgui_draw.cpp", "imgui_tables.cpp", "imgui_widgets.cpp",
                                       "backends/imgui_impl_sdl3.cpp", "backends/imgui_impl_opengl3.cpp")]
    third_party += glob(thorvg, "common/*.cpp", "renderer/*.cpp", "renderer/sw_engine/*.cpp", "loaders/svg/*.cpp", "loaders/raw/*.cpp")
    return app, third_party


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--debug", action="store_true", help="unoptimized build with debug info and runtime assertions")
    parser.add_argument("--clean", action="store_true", help="delete the object cache and output directory first")
    parser.add_argument("--out", default=str(WEB / "dist"), help="output directory (default: web/dist)")
    parser.add_argument("--fonts", choices=["default", "all"], default="default",
                        help="'default' preloads only the Japanese font and fetches the others on demand, 'all' preloads all of them (+33 MB)")
    parser.add_argument("-j", "--jobs", type=int, default=os.cpu_count() or 4)
    parser.add_argument("--serve", action="store_true", help="serve the output directory on http://localhost:8080 after building")
    args = parser.parse_args()

    empp, emcc = find_emscripten()
    mode = "debug" if args.debug else "release"
    obj_dir = WEB / "build" / mode
    out_dir = Path(args.out).resolve()
    if args.clean:
        shutil.rmtree(WEB / "build", ignore_errors=True)
        shutil.rmtree(out_dir, ignore_errors=True)
    obj_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)

    fetch_deps()
    app_sources, third_party_sources = collect_sources()

    common_flags = ["--use-port=sdl3", "-fwasm-exceptions"]
    common_flags += ["-O0", "-g"] if args.debug else ["-O2"]
    defines = [
        '-DIMGUI_USER_CONFIG="imgui/peepodrumkit_imconfig.h"',
        "-DPEEPO_DEBUG=(1)" if args.debug else "-DPEEPO_DEBUG=(0)",
        "-DPEEPO_RELEASE=(0)" if args.debug else "-DPEEPO_RELEASE=(1)",
        "-DTVG_STATIC",
    ]
    includes = [f"-I{p}" for p in (
        ROOT / "src", ROOT / "src" / "core", ROOT / "src" / "peepodrumkit", ROOT / "libs", DEPS,
        DEPS / "imgui", DEPS / "imgui" / "backends", DEPS / "thorvg" / "inc", DEPS / "thorvg_config",
        DEPS / "thorvg" / "src" / "common", DEPS / "thorvg" / "src" / "renderer", DEPS / "thorvg" / "src" / "renderer" / "sw_engine",
        DEPS / "thorvg" / "src" / "loaders" / "svg", DEPS / "thorvg" / "src" / "loaders" / "raw",
    )]
    cxx_flags = ["-std=c++23", "-Wno-nontrivial-memcall", "-Wno-deprecated-declarations"]

    # NOTE: Any header change simply rebuilds everything that includes project headers, good enough for a ~70 file project
    header_stamp = max((p.stat().st_mtime for p in list((ROOT / "src").rglob("*.h")) + [Path(__file__)]), default=0)

    jobs = []
    for source in app_sources + third_party_sources:
        is_app = source in app_sources
        is_c = source.suffix == ".c"
        is_thorvg = (DEPS / "thorvg") in source.parents
        if is_c:
            cmd = emcc + common_flags + defines + includes
        elif is_thorvg:
            # NOTE: ThorVG targets C++14 (its tvg::identity() collides with std::identity in C++20) and relies on transitive libc includes
            cmd = empp + common_flags + defines + includes + ["-std=c++17", "-include", "cstdlib", "-include", "cstring", "-w"]
        else:
            cmd = empp + common_flags + defines + includes + cxx_flags
        key = hashlib.sha1((str(source) + " ".join(cmd)).encode()).hexdigest()[:12]
        obj = obj_dir / f"{source.stem}_{key}.o"
        stale = (not obj.exists()) or obj.stat().st_mtime < source.stat().st_mtime or (is_app and obj.stat().st_mtime < header_stamp)
        jobs.append((source, obj, cmd + ["-c", str(source), "-o", str(obj)], stale))

    stale_jobs = [j for j in jobs if j[3]]
    print(f"[build] {mode}: compiling {len(stale_jobs)} of {len(jobs)} files with {args.jobs} jobs")
    failed = False
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = {pool.submit(run, cmd): (source, obj) for source, obj, cmd, _ in stale_jobs}
        for done, future in enumerate(concurrent.futures.as_completed(futures), 1):
            source, obj = futures[future]
            code, out = future.result()
            print(f"  [{done}/{len(stale_jobs)}] {source.relative_to(ROOT) if ROOT in source.parents else source.name}")
            if out.strip() and (code != 0 or args.debug):
                print(out)
            if code != 0:
                failed = True
                obj.unlink(missing_ok=True)
    if failed:
        sys.exit("error: compilation failed")

    preload = [
        (ROOT / "assets" / "audio", "/app/assets/audio"),
        (ROOT / "assets" / "graphics", "/app/assets/graphics"),
        (ROOT / "locales", "/app/locales"),
    ]
    fonts = sorted((ROOT / "assets").glob("*.otf"))
    for font in fonts:
        if args.fonts == "all" or font.name == DEFAULT_FONT:
            preload.append((font, f"/app/assets/{font.name}"))

    link = empp + common_flags + [str(obj) for _, obj, _, _ in jobs] + [
        "-o", str(out_dir / "peepodrumkit.js"),
        "-sMIN_WEBGL_VERSION=2", "-sMAX_WEBGL_VERSION=2",
        "-sALLOW_MEMORY_GROWTH=1", "-sINITIAL_MEMORY=268435456", "-sSTACK_SIZE=4194304",
        "-sFORCE_FILESYSTEM=1", "-lidbfs.js",
        "-sEXPORTED_FUNCTIONS=_main,_malloc,_free",
        "-sEXPORTED_RUNTIME_METHODS=ccall,cwrap,FS,UTF8ToString,stringToNewUTF8,lengthBytesUTF8",
        "-sENVIRONMENT=web",
        "--pre-js", str(WEB / "pdk_api.js"),
    ]
    if args.debug:
        link += ["-sASSERTIONS=2", "-sGL_ASSERTIONS=1"]
    for source, target in preload:
        link += ["--preload-file", f"{source}@{target}"]

    print("[build] linking")
    code, out = run(link, cwd=str(obj_dir))
    if out.strip():
        print(out)
    if code != 0:
        sys.exit("error: linking failed")

    # NOTE: The page itself, fonts that are fetched on demand and the third party license texts
    shutil.copyfile(WEB / "shell.html", out_dir / "index.html")
    (out_dir / "assets").mkdir(exist_ok=True)
    for font in fonts:
        target = out_dir / "assets" / font.name
        if args.fonts == "all" or font.name == DEFAULT_FONT:
            target.unlink(missing_ok=True)
        elif not target.exists() or target.stat().st_size != font.stat().st_size:
            shutil.copyfile(font, target)
    shutil.copytree(ROOT / "license_txt", out_dir / "license_txt", dirs_exist_ok=True)

    total = sum(p.stat().st_size for p in out_dir.iterdir() if p.is_file())
    print(f"[build] done: {out_dir} ({total / 1e6:.1f} MB excluding on demand fonts)")
    for name in ("index.html", "peepodrumkit.js", "peepodrumkit.wasm", "peepodrumkit.data"):
        path = out_dir / name
        print(f"  {name:22} {path.stat().st_size / 1e6:8.2f} MB" if path.exists() else f"  {name:22} MISSING")

    if args.serve:
        import functools
        import http.server
        handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(out_dir))
        handler.extensions_map = {**http.server.SimpleHTTPRequestHandler.extensions_map, ".wasm": "application/wasm"}
        print("[serve] http://localhost:8080  (Ctrl+C to stop)")
        http.server.ThreadingHTTPServer(("127.0.0.1", 8080), handler).serve_forever()


if __name__ == "__main__":
    main()
